"""Repository files -> filtered source -> code chunks -> embeddings -> FAISS index.

Pipeline (see README, "AI retrieval pipeline"):
  1. read_source_files()  : walk the workspace and drop irrelevant/unsafe files
  2. parse_source()       : Tree-sitter symbols (parser.py)
  3. create_chunks()      : one chunk per function/method/class header, plus module-level text
  4. embed_texts()        : Sentence Transformers vectors
  5. build_faiss_index()  : FAISS inner-product index over normalised vectors
  6. build_index()        : runs all of the above and writes the results to disk
BM25 is built from the saved chunks at search time (see search.py).
"""
from __future__ import annotations

import json
import os
import shutil
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from .parser import ParsedFile, detect_language, parse_source

# ---------------------------------------------------------------- filtering --
EXCLUDED_DIRS = {
    ".git", ".hg", ".svn", "node_modules", "bower_components", "vendor", "venv", ".venv", "env", "__pycache__",
    "site-packages", "dist", "build", "target", "out", ".next", ".nuxt", ".gradle", ".idea", ".vscode",
    "coverage", ".tox", ".mypy_cache", ".pytest_cache", ".cache", "bin", "obj", "staticfiles", ".terraform",
}
SOURCE_EXTENSIONS = {
    ".py", ".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx", ".java", ".go", ".rs", ".rb", ".php", ".c", ".h",
    ".cpp", ".hpp", ".cc", ".cs", ".kt", ".swift", ".scala", ".sh", ".sql", ".html", ".css", ".scss",
    ".json", ".yml", ".yaml", ".toml", ".md", ".txt", ".ini", ".cfg",
}
SOURCE_FILENAMES = {"dockerfile", "makefile"}
LOCK_OR_GENERATED_NAMES = {
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "pipfile.lock", "composer.lock",
    "cargo.lock", "gemfile.lock", "go.sum", "npm-shrinkwrap.json",
}
GENERATED_SUFFIXES = (".min.js", ".min.css", ".map", ".pb.go", "_pb2.py", ".bundle.js")
# Files that commonly contain secrets are never read, so they can never be sent to an LLM.
SECRET_NAMES = {".env", ".npmrc", ".pypirc", "id_rsa", "id_dsa", "id_ecdsa", "id_ed25519", ".netrc", "credentials"}
SECRET_SUFFIXES = (".pem", ".key", ".p12", ".pfx", ".jks", ".keystore", ".crt")
GENERATED_MARKERS = ("generated by", "code generated", "do not edit", "@generated", "auto-generated", "autogenerated")


@dataclass
class Limits:
    max_file_bytes: int = 300 * 1024
    max_files: int = 1500
    max_chunks: int = 8000
    max_chunk_lines: int = 80
    chunk_overlap_lines: int = 8


def is_candidate_path(rel_path: str) -> tuple[bool, str]:
    """Cheap, name-only check. Returns (keep, reason_if_skipped)."""
    parts = rel_path.split("/")
    name = parts[-1]
    lower = name.lower()
    if any(part in EXCLUDED_DIRS for part in parts[:-1]):
        return False, "excluded_directory"
    if lower in SECRET_NAMES or lower.startswith(".env") or lower.endswith(SECRET_SUFFIXES):
        return False, "possible_secret"
    if lower in LOCK_OR_GENERATED_NAMES or lower.endswith(GENERATED_SUFFIXES):
        return False, "generated_or_lock_file"
    dot = lower.rfind(".")
    if lower in SOURCE_FILENAMES or (dot != -1 and lower[dot:] in SOURCE_EXTENSIONS):
        return True, ""
    return False, "unsupported_type"


def inspect_content(data: bytes) -> tuple[bool, str]:
    """Content check on the first bytes: binary or generated files are skipped."""
    head = data[:4096]
    if b"\x00" in head:
        return False, "binary"
    top = head[:600].decode("utf-8", errors="ignore").lower()
    if any(marker in top for marker in GENERATED_MARKERS):
        return False, "generated_or_lock_file"
    return True, ""


def read_source_files(root: Path, limits: Limits | None = None) -> tuple[list[tuple[str, str]], dict]:
    """Walk `root` and return ([(relative_path, text)], skipped_counts)."""
    limits = limits or Limits()
    root = Path(root)
    files: list[tuple[str, str]] = []
    skipped: Counter = Counter()
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        dirnames[:] = sorted(d for d in dirnames if d not in EXCLUDED_DIRS)
        for filename in sorted(filenames):
            full = Path(dirpath) / filename
            rel = full.relative_to(root).as_posix()
            if full.is_symlink():
                skipped["symlink"] += 1
                continue
            keep, reason = is_candidate_path(rel)
            if not keep:
                skipped[reason] += 1
                continue
            try:
                size = full.stat().st_size
                if size == 0:
                    skipped["empty"] += 1
                    continue
                if size > limits.max_file_bytes:
                    skipped["file_too_large"] += 1
                    continue
                data = full.read_bytes()
            except OSError:
                skipped["unreadable"] += 1
                continue
            ok, reason = inspect_content(data)
            if not ok:
                skipped[reason] += 1
                continue
            if len(files) >= limits.max_files:
                skipped["file_limit_reached"] += 1
                continue
            files.append((rel, data.decode("utf-8", errors="replace")))
    return files, dict(skipped)


# ----------------------------------------------------------------- chunking --
def _window_chunks(lines: list[str], first_line: int, limits: Limits):
    """Split a run of lines into windows of max_chunk_lines with a small overlap."""
    step = max(1, limits.max_chunk_lines - limits.chunk_overlap_lines)
    for start in range(0, len(lines), step):
        piece = lines[start:start + limits.max_chunk_lines]
        if "".join(piece).strip():
            yield first_line + start, first_line + start + len(piece) - 1, "\n".join(piece)
        if start + limits.max_chunk_lines >= len(lines):
            break


def create_chunks(rel_path: str, text: str, parsed: ParsedFile, limits: Limits | None = None) -> list[dict]:
    """Turn one file into chunks. Parsed files get symbol-aware chunks; others get line windows."""
    limits = limits or Limits()
    lines = text.splitlines()
    chunks: list[dict] = []

    def add(start: int, end: int, kind: str, symbol: str, body_lines: list[str] | None = None):
        body = body_lines if body_lines is not None else lines[start - 1:end]
        for s, e, piece in _window_chunks(body, start, limits):
            chunks.append({"path": rel_path, "language": parsed.language, "start_line": s, "end_line": e,
                           "kind": kind, "symbol": symbol, "text": piece})

    if not parsed.parsed or not parsed.symbols:
        add(1, len(lines), "text", "")
    else:
        cursor = 1  # first line not yet covered

        def emit(symbol, prefix: str):
            qualified = f"{prefix}{symbol.name}"
            if symbol.children:  # class: header up to the first method, then each method
                add(symbol.start_line, symbol.children[0].start_line - 1, symbol.kind, qualified)
                for child in symbol.children:
                    emit(child, qualified + ".")
            else:
                add(symbol.start_line, symbol.end_line, symbol.kind, qualified)

        for top in sorted(parsed.symbols, key=lambda s: s.start_line):
            if top.start_line > cursor:  # imports, constants, top-level statements
                add(cursor, top.start_line - 1, "module", "")
            emit(top, "")
            cursor = max(cursor, top.end_line + 1)
        if cursor <= len(lines):
            add(cursor, len(lines), "module", "")
    return chunks


# --------------------------------------------------------------- embeddings --
class SemanticSearchUnavailable(RuntimeError):
    """Raised when sentence-transformers / FAISS cannot be used."""


_embedder_cache: dict[str, object] = {}


def get_embedder(model_name: str):
    """Load (and cache) a Sentence Transformers model. First use downloads the model."""
    if model_name not in _embedder_cache:
        try:
            from sentence_transformers import SentenceTransformer
        except ImportError as exc:
            raise SemanticSearchUnavailable("sentence-transformers is not installed (pip install sentence-transformers).") from exc
        try:
            _embedder_cache[model_name] = SentenceTransformer(model_name)
        except Exception as exc:
            raise SemanticSearchUnavailable(f"Could not load embedding model '{model_name}': {type(exc).__name__}") from exc
    return _embedder_cache[model_name]


def chunk_to_embedding_text(chunk: dict) -> str:
    return f"{chunk['path']}\n{chunk.get('symbol', '')}\n{chunk['text']}"[:2000]


def embed_texts(texts: list[str], embedder=None, model_name: str = "sentence-transformers/all-MiniLM-L6-v2"):
    """Return L2-normalised float32 vectors. `embedder` can be any object with .encode()."""
    import numpy as np

    embedder = embedder or get_embedder(model_name)
    vectors = embedder.encode(texts, batch_size=32, show_progress_bar=False, convert_to_numpy=True)
    vectors = np.asarray(vectors, dtype="float32")
    norms = np.linalg.norm(vectors, axis=1, keepdims=True)
    norms[norms == 0] = 1.0
    return vectors / norms


def build_faiss_index(vectors):
    try:
        import faiss
    except ImportError as exc:
        raise SemanticSearchUnavailable("faiss-cpu is not installed (pip install faiss-cpu).") from exc
    index = faiss.IndexFlatIP(vectors.shape[1])  # inner product == cosine similarity on normalised vectors
    index.add(vectors)
    return index


# ------------------------------------------------------------------ driver --
def build_index(source_dir: Path, index_dir: Path, limits: Limits | None = None, *, use_semantic: bool = True,
                embedder=None, model_name: str = "sentence-transformers/all-MiniLM-L6-v2") -> dict:
    """Run the whole pipeline and write chunks.json, overview.json and (optionally) faiss.index."""
    limits = limits or Limits()
    files, skipped = read_source_files(source_dir, limits)
    if not files:
        raise ValueError("No readable source files were found after filtering.")

    chunks: list[dict] = []
    overview_files: list[dict] = []
    languages: Counter = Counter()
    symbol_counts: Counter = Counter()
    for rel, text in files:
        parsed = parse_source(rel, text)
        languages[parsed.language] += 1
        symbols = parsed.flat_symbols()
        for s in symbols:
            symbol_counts[s.kind] += 1
        overview_files.append({
            "path": rel, "language": parsed.language, "lines": text.count("\n") + 1,
            "parsed_with_tree_sitter": parsed.parsed,
            "symbols": [s.to_dict() for s in symbols[:200]],
        })
        for chunk in create_chunks(rel, text, parsed, limits):
            if len(chunks) >= limits.max_chunks:
                skipped["chunk_limit_reached"] = skipped.get("chunk_limit_reached", 0) + 1
                continue
            chunks.append(chunk)
    for i, chunk in enumerate(chunks):
        chunk["id"] = i

    semantic = {"indexed": False, "error": None, "model": None}
    index_dir = Path(index_dir)
    tmp_dir = index_dir.with_name(index_dir.name + ".tmp")
    shutil.rmtree(tmp_dir, ignore_errors=True)
    tmp_dir.mkdir(parents=True)

    if use_semantic:
        try:
            import faiss

            vectors = embed_texts([chunk_to_embedding_text(c) for c in chunks], embedder, model_name)
            faiss.write_index(build_faiss_index(vectors), str(tmp_dir / "faiss.index"))
            semantic = {"indexed": True, "error": None, "model": model_name}
        except SemanticSearchUnavailable as exc:
            semantic["error"] = str(exc)
        except Exception as exc:  # keep keyword search working even if embedding fails
            semantic["error"] = f"Semantic indexing failed: {type(exc).__name__}"

    overview = {
        "total_files": len(files), "total_chunks": len(chunks), "languages": dict(languages),
        "symbol_counts": dict(symbol_counts), "skipped": skipped, "files": overview_files, "semantic": semantic,
    }
    (tmp_dir / "chunks.json").write_text(json.dumps(chunks), encoding="utf-8")
    (tmp_dir / "overview.json").write_text(json.dumps(overview), encoding="utf-8")
    shutil.rmtree(index_dir, ignore_errors=True)
    index_dir.parent.mkdir(parents=True, exist_ok=True)
    tmp_dir.rename(index_dir)
    return {k: overview[k] for k in ("total_files", "total_chunks", "languages", "symbol_counts", "skipped", "semantic")}


def load_overview(index_dir: Path) -> dict | None:
    path = Path(index_dir) / "overview.json"
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))
