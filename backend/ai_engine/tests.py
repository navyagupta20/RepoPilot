# ----------------------------------------------------------------- bug signals --
def test_error_signal_extraction():
    trace = ('Traceback (most recent call last):\n  File "/app/auth/views.py", line 42, in login\n    x\n'
             'KeyError: \'token\'\n  at Object.run (/srv/web/app.js:10:5)\n  at com.acme.Main.go(Main.java:77)')
    signals = bug_analyzer.extract_error_signals(trace)
    assert {"path": "/app/auth/views.py", "line": 42, "function": "login"} in signals["frames"]
    assert any(f["path"].endswith("app.js") and f["line"] == 10 for f in signals["frames"])
    assert any(f["path"] == "Main.java" and f["line"] == 77 for f in signals["frames"])
    assert signals["exceptions"] == ["KeyError"] and signals["message"].startswith("KeyError")
    assert bug_analyzer.extract_error_signals("it is just slow")["frames"] == []


def test_stack_frames_pull_in_the_exact_chunk(built_index):
    src, idx = built_index
    build_index(src, idx, use_semantic=False)
    signals = bug_analyzer.extract_error_signals('File "/home/u/proj/auth/session.py", line 5, in verify_password\nTypeError: bad')
    chunks = search.load_index(idx).chunks
    hits = bug_analyzer.chunks_for_frames(chunks, signals["frames"])
    assert len(hits) == 1 and hits[0]["symbol"] == "verify_password" and hits[0]["source"] == "stack_trace"
    assert bug_analyzer.chunks_for_frames(chunks, [{"path": "other/unknown.py", "line": 5, "function": ""}]) == []


