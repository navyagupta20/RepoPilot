PY = '''import os

@cache
def top(a):
    def inner():
        pass
    return a

class Service:
    """Doc."""
    limit = 3

    def run(self):
        return 1

    def stop(self):
        return 2
'''


def test_python_symbols_extracted_with_tree_sitter():
    parsed = parse_source("svc.py", PY)
    assert parsed.parsed is True
    flat = [(s.name, s.kind) for s in parsed.flat_symbols()]
    assert flat == [("top", "function"), ("Service", "class"), ("run", "function"), ("stop", "function")]
    assert [c.name for c in parsed.symbols[1].children] == ["run", "stop"]  # methods nest under their class
    top = parsed.symbols[0]
    assert top.start_line == 3  # decorator line is included


def test_unsupported_language_is_not_claimed_as_parsed():
    parsed = parse_source("lib.rs", "fn main() {}\n")
    assert parsed.parsed is False and parsed.symbols == [] and parsed.language == "rust"
    chunks = create_chunks("lib.rs", "fn main() {}\n", parsed)
    assert len(chunks) == 1 and chunks[0]["kind"] == "text"


def test_symbol_aware_chunks_name_methods_with_their_class():
    parsed = parse_source("svc.py", PY)
    chunks = create_chunks("svc.py", PY, parsed)
    symbols = [c["symbol"] for c in chunks]
    assert {"top", "Service", "Service.run", "Service.stop"} <= set(symbols)
    assert any(c["kind"] == "module" and "import os" in c["text"] for c in chunks)
    run = next(c for c in chunks if c["symbol"] == "Service.run")
    assert "return 1" in run["text"] and run["start_line"] == 13


def test_long_text_is_windowed_with_overlap():
    text = "\n".join(f"line {i}" for i in range(200))
    chunks = create_chunks("notes.txt", text, parse_source("notes.txt", text), Limits(max_chunk_lines=50, chunk_overlap_lines=5))
    assert len(chunks) > 3
    assert chunks[1]["start_line"] == chunks[0]["end_line"] - 4  # overlap


