def test_hybrid_search_with_faiss_index(built_index):
    src, idx = built_index
    embedder = HashingEmbedder()
    summary = build_index(src, idx, use_semantic=True, embedder=embedder)
    assert summary["semantic"]["indexed"] is True and (idx / "faiss.index").exists()
    out = search.hybrid_search(idx, "verify password hash", mode="hybrid", embedder=embedder)
    assert out["mode_used"] == "hybrid" and out["note"] == ""
    top = out["results"][0]
    assert top["path"] == "auth/session.py" and top["keyword_rank"] and top["semantic_rank"]
    semantic_only = search.hybrid_search(idx, "docker compose deployment", mode="semantic", embedder=embedder)
    assert semantic_only["mode_used"] == "semantic" and semantic_only["results"][0]["path"] == "notes.txt"


def test_reciprocal_rank_fusion_rewards_agreement():
    fused = search.reciprocal_rank_fusion([[1, 2, 3], [3, 1, 4]])
    order = [cid for cid, _ in fused]
    assert order[:2] == [1, 3] and set(order) == {1, 2, 3, 4}


