def test_content_filter_detects_binary_and_generated_files():
    assert inspect_content(b"print('hi')\n")[0] is True
    assert inspect_content(b"\x89PNG\r\n\x00\x00data")[0] is False
    assert inspect_content(b"# Code generated by protoc. DO NOT EDIT.\nx = 1\n") == (False, "generated_or_lock_file")


def test_read_source_files_applies_all_filters(tmp_path):
    (tmp_path / "keep.py").write_text("x = 1\n")
    (tmp_path / "node_modules").mkdir()
    (tmp_path / "node_modules" / "dep.js").write_text("x=1")
    (tmp_path / ".env").write_text("SECRET=abc")
    (tmp_path / "big.py").write_text("x = 1\n" * 100_000)
    (tmp_path / "blob.py").write_bytes(b"\x00\x01\x02")
    (tmp_path / "empty.py").write_text("")
    (tmp_path / "gen.py").write_text("# @generated\nx = 1\n")
    (tmp_path / "link.py").symlink_to(tmp_path / "keep.py")
    files, skipped = read_source_files(tmp_path, Limits(max_file_bytes=10_000))
    assert [p for p, _ in files] == ["keep.py"]
    assert skipped["file_too_large"] == 1 and skipped["binary"] == 1 and skipped["possible_secret"] == 1
    assert skipped["empty"] == 1 and skipped["generated_or_lock_file"] == 1 and skipped["symlink"] == 1


def test_file_count_limit(tmp_path):
    for i in range(10):
        (tmp_path / f"f{i}.py").write_text(f"x = {i}\n")
    files, skipped = read_source_files(tmp_path, Limits(max_files=3))
    assert len(files) == 3 and skipped["file_limit_reached"] == 7


