class _Resp:
    def __init__(self, status=200, payload=None):
        self.status_code, self._payload = status, payload

    def json(self):
        if isinstance(self._payload, Exception):
            raise self._payload
        return self._payload


def _configure(monkeypatch, provider):
    monkeypatch.setenv("LLM_PROVIDER", provider)
    monkeypatch.setenv("LLM_API_KEY", "sk-secret-value")
    monkeypatch.setenv("LLM_MODEL", "some-model")


def test_openai_compatible_request_and_parsing(clean_llm_env):
    _configure(clean_llm_env, "openai_compatible")
    seen = {}

    def fake_post(url, headers=None, json=None, timeout=None):
        seen.update(url=url, headers=headers, body=json)
        return _Resp(200, {"choices": [{"message": {"content": "  hello  "}}]})

    clean_llm_env.setattr(llm.requests, "post", fake_post)
    assert llm.generate("sys", "usr") == "hello"
    assert seen["url"].endswith("/chat/completions") and seen["headers"]["authorization"] == "Bearer sk-secret-value"
    assert seen["body"]["model"] == "some-model" and seen["body"]["messages"][0] == {"role": "system", "content": "sys"}


def test_anthropic_request_and_parsing(clean_llm_env):
    _configure(clean_llm_env, "anthropic")
    seen = {}

    def fake_post(url, headers=None, json=None, timeout=None):
        seen.update(url=url, headers=headers, body=json)
        return _Resp(200, {"content": [{"type": "text", "text": "part1 "}, {"type": "text", "text": "part2"}]})

    clean_llm_env.setattr(llm.requests, "post", fake_post)
    assert llm.generate("sys", "usr") == "part1 part2"
    assert seen["url"].endswith("/v1/messages") and seen["headers"]["x-api-key"] == "sk-secret-value" and seen["body"]["system"] == "sys"


@pytest.mark.parametrize("status,fragment", [(401, "API key"), (403, "API key"), (404, "LLM_MODEL"), (429, "rate limit"), (503, "problems")])
def test_provider_http_errors_become_friendly_messages_without_secrets(clean_llm_env, status, fragment):
    _configure(clean_llm_env, "openai_compatible")
    clean_llm_env.setattr(llm.requests, "post", lambda *a, **k: _Resp(status, {"error": "sk-secret-value leaked?"}))
    with pytest.raises(llm.LLMError) as exc:
        llm.generate("s", "u")
    assert fragment in str(exc.value) and "sk-secret-value" not in str(exc.value)


