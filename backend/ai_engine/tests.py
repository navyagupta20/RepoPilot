class HashingEmbedder:
    """Deterministic stand-in for Sentence Transformers: a bag-of-words hashed into 128 dimensions."""

    def encode(self, texts, **kwargs):
        out = np.zeros((len(texts), 128), dtype="float32")
        for row, text in enumerate(texts):
            for token in search.tokenize(text):
                out[row, zlib.crc32(token.encode()) % 128] += 1.0
        return out


